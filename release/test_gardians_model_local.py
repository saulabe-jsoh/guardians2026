results = []
level_counts = {"🟢 Level 0~4 (저위험)": 0, "🟡 Level 5~7 (중위험)": 0, "🔴 Level 8~10 (고위험)": 0}

print("📝 110건 샘플 텍스트 위험도 예측 결과\n")

for i, text in enumerate(test_samples, 1):
    onnx_input = np.array([[text]], dtype=object)
    # 기존 코드
    # pred = sess.run([label_name], {input_name: onnx_input})
    # raw_score = float(pred[0][0])

    # ⬇️ 새롭게 변경할 코드 ⬇️
    # ONNX 분류 모델은 두 번째 출력 노드에서 클래스별 확률 배열을 반환합니다.
    prob_name = sess.get_outputs()[1].name
    pred_probs = sess.run([prob_name], {input_name: onnx_input})[0][0]  # 예: [0.1, 0.7, 0.2]

    # 확률 기대값으로 연속적인 위험도 점수 산출 (저:0.1, 중:0.6, 고:0.9)
    score_map = np.array([0.1, 0.6, 0.9])
    raw_score = float(np.sum(pred_probs * score_map))
    risk_score = min(1.0, max(0.0, round(raw_score, 1)))
    level = int(risk_score * 10)

    if level >= 8:
        badge = "🔴 [긴급/심각]"
        level_counts["🔴 Level 8~10 (고위험)"] += 1
    elif level >= 5:
        badge = "🟡 [위험/경계]"
        level_counts["🟡 Level 5~7 (중위험)"] += 1
    else:
        badge = "🟢 [일반/안전]"
        level_counts["🟢 Level 0~4 (저위험)"] += 1

    results.append({"텍스트": text, "예측 위험도": risk_score, "Level": level, "분류": badge})

    # 처음 10건(일상 대화)은 모두 출력하고, 이후는 5건마다 출력
    if i <= 10 or i % 5 == 0:
        print(f"[{i:03d}] {text[:35]}... ➡️ 예측 위험도: {risk_score:.1f} {badge}")

print("\n" + "=" * 80)
print("📊 [모델 예측 결과 요약 리포트]")
print("=" * 80)
for k, v in level_counts.items():
    print(f" - {k}: {v}건")

df_res = pd.DataFrame(results)
